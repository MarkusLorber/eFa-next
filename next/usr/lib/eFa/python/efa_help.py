_YES_TAIL = re.compile(r'(?::|,)? *(?:type (?:ja or )?yes|yes, else empty|yes or empty)(?=$|,)', re.I)
_CLI_PART = re.compile(r'^(?:or )?empty\b|^- (?:for none|empties)', re.I)


def web_label(label, kind=None):
    """A field label of the command table as the web form shows it. The console rules leave the label: "empty keeps it"
    goes into the placeholder, "- for none" becomes a tick box Clear (clear), "type yes" a tick box (yes)."""
    if kind == 'confirm' or label in YES_LABELS:
        if label in YES_LABELS:
            return {'label': YES_LABELS[label], 'placeholder': '', 'clear': False, 'yes': True}
        if label.startswith('Type yes to confirm: '):
            return {'label': 'Yes, do it: ' + label[len('Type yes to confirm: '):], 'placeholder': '', 'clear': False, 'yes': True}
    label = label.replace(': type yes, ', ': ')
    yes = bool(_YES_TAIL.search(label)) or label.startswith('yes: ') or label.startswith('Own server: it stands in the EU')
    if yes:
        label = _YES_TAIL.sub('', label)
        label = label[len('yes: '):].capitalize() if label.startswith('yes: ') else label
    parts = re.split(r'(, |; )', label)
    kept, tails, clear = [parts[0]], [], False
    for sep, part in zip(parts[1::2], parts[2::2]):
        if re.match(r'- (?:for none|empties)', part):
            clear = True
        elif part.startswith('- '):
            continue  # another use of - on the console (such as stdout): no tick box, it would not clear anything
        elif _CLI_PART.match(part) and part.count(')') <= part.count('('):
            tails.append(part[0].upper() + part[1:])
        else:
            kept += [sep, part]
    return {'label': ''.join(kept).strip(), 'placeholder': '; '.join(tails), 'clear': clear, 'yes': yes}


