TITLE_TAILS = (': settings', ': switch', ': show', ': status', ': list', ': set')


def short_title(title):
    """The title of a card without the tail that only names the command, such as ': switch'; the switch is in the card head."""
    for tail in TITLE_TAILS:
        if title.endswith(tail):
            return title[:-len(tail)]
    return title


def first_sentence(text):
    """The first sentence of a help text, for the line under the title; the whole text stays in the popup."""
    for end in ('. ', '? ', '! '):
        cut = text.find(end)
        if 0 < cut < len(text) - 2:
            return text[:cut + 1]
    return text


